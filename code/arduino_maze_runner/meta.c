// NOTE: From project directory:
// tcc -run meta.c

#define BASE_WINDOWS_H
#include <Windows.h>

#define BASE_IMPLEMENTATION
#include "../base.h"

#include "meta.h"

int
main (void) {
  Arena *arena = arena_alloc_default();
  printf("Generating trig lookup tables...\n");
  printf("Using a scaling factor of %d and %d-bit angle resolution.\n", TRIG_SCALING_FACTOR, TRIG_INDEX_BITS);

  u8 current_directory[PATH_MAX];
  u32 chars_written = GetCurrentDirectory(PATH_MAX, current_directory);
  Assert(chars_written > 0);
  Str8 base_path = Str8CStr(current_directory);
  Str8_List path = {0};
  str8_list_push(arena, &path, base_path);
  str8_list_push(arena, &path, Str8Lit("/generated"));
  Str8 generated_path = str8_list_join(arena, path, NULL);

  bool directory_create_result = CreateDirectory(str8_to_cstr(arena, generated_path), NULL);
  if (!directory_create_result) {
    if (GetLastError() != ERROR_ALREADY_EXISTS) {
      printf("Unable to create output directory!\n");
      return 1;
    }
  }

  Str8_List trig_lookup_builder = {0};
  str8_list_pushf(arena, &trig_lookup_builder, "// NOTE: Generated by %.*s\\%s\n\n", Str8Expand(base_path), __FILE__);
  {
    Str8_List sin_lut = {0};
    str8_list_push(arena, &sin_lut, Str8Lit("global s16 sin_lookup[] = {\n\t"));
    f64 rad_step = (M_PI / 2.0) / TRIG_INDEX_MAX;
    for (int i = 0; i <= TRIG_INDEX_MAX + 1; ++i) {
      if (i > 0) {
        str8_list_push(arena, &sin_lut, Str8Lit(", "));
        if (i % VALUES_PER_LINE == 0) {
          str8_list_push(arena, &sin_lut, Str8Lit("\n\t"));
        }
      }
      s16 value = (s16)lround(sin(i * rad_step) * TRIG_SCALING_FACTOR);
      str8_list_pushf(arena, &sin_lut, "%d", value);
    }
    str8_list_push(arena, &sin_lut, Str8Lit("\n};"));
    str8_list_concat(&trig_lookup_builder, &sin_lut);


    Str8_List atan_lut = {0};
  }

  Str8 trig_lookup_file = str8_list_join(arena, trig_lookup_builder, NULL);

  str8_list_push(arena, &path, Str8Lit("/trig_lookup.cpp"));
  Str8 file_path = str8_list_join(arena, path, NULL);
  HANDLE output = CreateFile(str8_to_cstr(arena, file_path), GENERIC_WRITE, 0, NULL, CREATE_ALWAYS, FILE_ATTRIBUTE_NORMAL, NULL);
  if (output == INVALID_HANDLE_VALUE) {
    printf("Unable to create output file(s)!\n");
    return 1;
  }
  DWORD bytes_written;
  bool success = WriteFile(output, trig_lookup_file.str, trig_lookup_file.count, &bytes_written, NULL);
  if (!success || bytes_written != trig_lookup_file.count) {
    printf("Unable to write to output file(s)!\n");
    return 1;
  }


  return 0;
}